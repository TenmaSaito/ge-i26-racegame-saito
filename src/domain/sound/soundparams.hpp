#pragma once
// ============================================================================
// soundparams.hpp ― 音の「状態」を表す値の型 (アプリ層 → 音声層の受け渡し用)
// 役割: ゲーム側が「いまエンジンは何回転で、どれだけ踏んでいるか」
//       「タイヤはどれだけ深く、どれだけ長く滑っているか」を伝えるための
//       ただのデータ。再生方法 (波形・ミキサー・デバイス) は一切含まない。
// 依存: なし (標準ライブラリすら不要)。どのプラットフォームでも同じ。
// ============================================================================

// エンジン音の状態。毎フレーム最新値を送ればよい (音声側で滑らかにつなぐ)。
struct EngineSound {
    bool running = false;   // false で静かにフェードアウト (レース外・ポーズ)
    float rpm = 0.0f;       // 回転数 (rpm)。アイドル〜レッドゾーンの実数値
    float rpmNorm = 0.0f;   // 回転数の正規化値 0 (アイドル) 〜 1 (レッドゾーン)
    float throttle = 0.0f;  // アクセル開度 0..1 (音の張り・明るさ)
    float load = 0.0f;      // エンジン負荷 0..1 (シフト中や空転で下がる)
};

// タイヤ (ドリフト / 横滑り) 音の状態。
struct TireSound {
    float depth = 0.0f;     // 滑りの深さ 0 (グリップ) 〜 1 (深いドリフト)
    float duration = 0.0f;  // 滑りが続いている秒数 (出だしと持続で音色が変わる)
    float speed = 0.0f;     // 車速 (m/s)。速いほど音程が上がり、音量も出る
};

// 単発の効果音 (合図)。
enum class SoundCue {
    CountdownTick,  // カウントダウンの 3・2・1 (低い電子音)
    CountdownGo,    // スタート (高く長い電子音)
};
